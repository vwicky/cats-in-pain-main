def parse_model_dirs(args: argparse.Namespace) -> list[Path]:
    dirs = [Path(x).expanduser().resolve() for x in args.model_dirs]
    if args.model_dirs_json:
        with open(args.model_dirs_json, 'r') as f:
            json_dirs = json.load(f)
        if not isinstance(json_dirs, list):
            raise ValueError('--model-dirs-json must be a JSON list')
        dirs.extend([Path(x).expanduser().resolve() for x in json_dirs])
    dirs = list(dict.fromkeys(dirs))
    if len(dirs) != 45:
        raise ValueError(f'Expected 45 model directories, got {len(dirs)}')
    return sorted(dirs)


def load_pair_meta(model_dir: Path) -> dict[str, Any]:
    p = model_dir / 'pair_meta.json'
    if not p.exists():
        raise FileNotFoundError(f'missing pair_meta.json: {p}')
    with open(p, 'r') as f:
        return json.load(f)


def read_training_best_epoch(model_dir: Path) -> int | None:
    train = model_dir / 'training'
    for name in ('run_summary.json', 'fold_summary.json'):
        p = train / name
        if not p.is_file():
            continue
        try:
            with open(p, encoding='utf-8') as f:
                d = json.load(f)
        except json.JSONDecodeError:
            continue
        be = d.get('best_epoch')
        if be is not None:
            return int(be)
    return None


def filter_model_dirs_by_min_best_epoch(
    model_dirs: list[Path],
    min_best_epoch: int,
    logger: logging.Logger,
) -> tuple[list[Path], dict[str, Any]]:
    kept: list[Path] = []
    dropped: list[dict[str, Any]] = []
    kept_meta: list[dict[str, Any]] = []
    for d in sorted(model_dirs, key=lambda x: str(x)):
        meta = load_pair_meta(d)
        neg = meta.get('class_neg_label_int_0')
        pos = meta.get('class_pos_label_int_1')
        if neg is None or pos is None:
            raise ValueError(f'pair_meta missing class fields in {d}')
        a, b = str(neg), str(pos)
        pair = f'{min(a, b)}|{max(a, b)}'
        be = read_training_best_epoch(d)
        if be is None:
            logger.warning(
                'Pair %s: no training/run_summary.json best_epoch under %s; keeping model',
                pair,
                d,
            )
            kept.append(d)
            kept_meta.append({'pair': pair, 'path': str(d), 'best_epoch': None})
            continue
        if be < min_best_epoch:
            logger.info(
                'Dropping pair %s: best_epoch=%d < min_best_epoch=%d (%s)',
                pair,
                be,
                min_best_epoch,
                d,
            )
            dropped.append({'pair': pair, 'path': str(d), 'best_epoch': be})
        else:
            kept.append(d)
            kept_meta.append({'pair': pair, 'path': str(d), 'best_epoch': be})
    report: dict[str, Any] = {
        'min_best_epoch': min_best_epoch,
        'best_epoch_convention': (
            '0-based index in training/run_summary.json (training_loop early-stopping checkpoint epoch)'
        ),
        'n_input': len(model_dirs),
        'n_kept': len(kept),
        'n_dropped': len(dropped),
        'dropped_pairs': dropped,
        'kept_pairs': kept_meta,
    }
    return sorted(kept), report


def filter_model_dirs_pain_pairs_only(
    model_dirs: list[Path],
    pain_class: str,
    logger: logging.Logger,
) -> tuple[list[Path], dict[str, Any]]:
    """Keep only ``binary__*`` dirs whose OvO pair includes ``pain_class`` (e.g. Paining)."""
    pain_class = str(pain_class).strip()
    kept: list[Path] = []
    skipped_meta: list[dict[str, str]] = []
    for d in sorted(model_dirs, key=lambda x: str(x)):
        meta = load_pair_meta(d)
        neg = str(meta.get('class_neg_label_int_0', ''))
        pos = str(meta.get('class_pos_label_int_1', ''))
        if pain_class not in (neg, pos):
            a, b = neg, pos
            pair = f'{min(a, b)}|{max(a, b)}'
            skipped_meta.append({'pair': pair, 'path': str(d)})
            continue
        kept.append(d)
    report: dict[str, Any] = {
        'pain_class': pain_class,
        'n_input': len(model_dirs),
        'n_kept': len(kept),
        'n_skipped_non_pain_pair': len(skipped_meta),
        'skipped_pairs': skipped_meta,
        'kept_paths': [str(x) for x in sorted(kept)],
    }
    logger.info(
        'Pain-pair subset: kept %d / %d dirs involving %r (expect 9 for C(10,2) pain rows)',
        len(kept),
        len(model_dirs),
        pain_class,
    )
    if len(kept) != 9:
        logger.warning(
            'Pain-pair count is %d (expected 9 when all pain OvO checkpoints are present)',
            len(kept),
        )
    return sorted(kept), report


def _infer_pose_version(resolved_path: str, cfg: dict[str, Any]) -> str:
    """Match ``data_loading.load_dataset`` heuristics (v1 vs v2)."""
    pose_v1_rel = Path(str(cfg['data']['pose_v1_dir']))
    pose_v2_rel = Path(str(cfg['data']['pose_v2_dir']))
    if not pose_v1_rel.is_absolute():
        pose_v1_rel = REPO_ROOT / pose_v1_rel
    if not pose_v2_rel.is_absolute():
        pose_v2_rel = REPO_ROOT / pose_v2_rel
    pfull = Path(resolved_path) if Path(resolved_path).is_absolute() else REPO_ROOT / resolved_path
    try:
        rp = pfull.resolve()
        v1root = pose_v1_rel.resolve()
        v2root = pose_v2_rel.resolve()
        if v1root in rp.parents or rp == v1root:
            return 'v1'
        if v2root in rp.parents or rp == v2root:
            return 'v2'
        s = str(rp).replace('\\', '/')
        if 'superanimal_v2' in s or '/pose/v2' in s.lower():
            return 'v2'
        if 'labeled' in s or '/pose/labeled' in s:
            return 'v1'
    except ValueError:
        pass
    return 'v2'


def _mask_rel_if_exists(raw_m: Any) -> str | None:
    if raw_m is None or (isinstance(raw_m, float) and pd.isna(raw_m)):
        return None
    m = _to_repo_relative(str(raw_m).strip()) if str(raw_m).strip() else None
    return m if m and pose_file_exists(m) else None


def _resolve_pose_row(row: pd.Series, pose_index: dict, pose_v1_rel: Path, cfg: dict[str, Any]) -> tuple[str | None, str, str | None]:
    sid = row.get('snippet_id')
    raw_pose = row.get('pose_path')
    if raw_pose is None or (isinstance(raw_pose, float) and pd.isna(raw_pose)):
        raw_pose = None
    rel_pose = _to_repo_relative(str(raw_pose).strip()) if raw_pose and str(raw_pose).strip() else None
    resolved: str | None = None
    version = 'v2'
    mask_rel: str | None = None

    if pose_index and isinstance(sid, str):
        ent = pose_index.get(sid)
        st = str(ent.get('status', '')).lower() if ent else ''
        if ent and st == 'done':
            rp = _to_repo_relative(ent.get('pose_path'))
            rm = _to_repo_relative(ent.get('pose_mask_path')) if ent.get('pose_mask_path') else None
            if rp and pose_file_exists(rp):
                resolved = rp
                version = _infer_pose_version(resolved, cfg)
                mask_rel = rm if rm and pose_file_exists(rm) else None

    if resolved is None and rel_pose and pose_file_exists(rel_pose):
        resolved = rel_pose
        version = _infer_pose_version(resolved, cfg)
        mask_rel = _mask_rel_if_exists(row.get('pose_mask_path'))
    elif resolved is None:
        if isinstance(sid, str) and sid:
            v1 = resolve_v1_pose(sid, pose_v1_rel)
            if v1 and pose_file_exists(v1):
                resolved = v1
                version = 'v1'
                v1m = pose_v1_rel / f'{sid}_pose_mask.npy'
                v1m_rel = str(v1m).replace('\\', '/')
                mask_rel = v1m_rel if pose_file_exists(v1m_rel) else _mask_rel_if_exists(row.get('pose_mask_path'))
    return resolved, version, mask_rel


def _apply_vitpose_qc(df: pd.DataFrame, cfg: dict[str, Any], logger: logging.Logger) -> pd.DataFrame:
    ddata = cfg.get('data')
    vq = ddata.get('vitpose_qc') if isinstance(ddata, dict) else None
    vq = vq if isinstance(vq, dict) else {}
    if not (vq.get('filter', False) or vq.get('attach_enrichment_columns', False)):
        return df
    from vitpose_qc import  load_vitpose_enrichment

    rel = str(vq.get('enrichment', 'src/dataset_construction/reports/vitpose_qc_enrichment.jsonl')).strip()
    enr_path = Path(rel) if Path(rel).is_absolute() else REPO_ROOT / rel
    enr = load_vitpose_enrichment(enr_path)
    if vq.get('filter', False) and not enr:
        raise FileNotFoundError(
            f"data.vitpose_qc.filter is true but enrichment is missing or empty: {enr_path}"
        )
    default_ok = bool(vq.get('default_ok_if_missing', True))
    n_before = len(df)

    if vq.get('attach_enrichment_columns', False) and enr:
        df = df.copy()

        def _e(sid) -> dict:
            return enr.get(str(sid)) or {}

        def _qok(sid) -> bool:
            if str(sid) in enr:
                return bool(_e(sid).get('vitpose_qc_ok', True))
            return default_ok

        df['vitpose_mean_conf'] = df['snippet_id'].map(lambda s: _e(s).get('mean_conf'))
        df['vitpose_y_range'] = df['snippet_id'].map(lambda s: _e(s).get('y_range'))
        df['vitpose_qc_ok'] = df['snippet_id'].map(_qok)

    if vq.get('filter', False) and enr:

        def _kept(sid) -> bool:
            r = enr.get(str(sid))
            if r is None:
                return default_ok
            return bool(r.get('vitpose_qc_ok', True))

        m = df['snippet_id'].map(_kept)
        n_drop = int((~m).sum())
        df = df.loc[m].copy()
        logger.info(
            'ViTPose QC: kept %d / %d (dropped %d) using %s; default_ok_if_missing=%s',
            len(df),
            n_before,
            n_drop,
            enr_path,
            default_ok,
        )
    return df


def load_holdout_dataset(args: argparse.Namespace, cfg: dict[str, Any], logger: logging.Logger) -> pd.DataFrame:
    """Load holdout JSONL; resolve ViTPose paths; optional audio + ViTPose QC (from cfg)."""
    holdout_path = Path(str(args.holdout_manifest)).expanduser().resolve()
    if not holdout_path.is_file():
        raise FileNotFoundError(
            f'--holdout-manifest not found (use a real JSONL path): {holdout_path}'
        )
    if holdout_path.stat().st_size == 0:
        raise ValueError(f'Holdout manifest is empty: {holdout_path}')
    with open(holdout_path, encoding='utf-8') as f:
        holdout = pd.read_json(f, lines=True)

    if 'snippet_id' not in holdout.columns:
        raise ValueError('holdout manifest must contain snippet_id')
    if 'video_id' not in holdout.columns:
        raise ValueError('holdout manifest must contain video_id')
    label_field = str(cfg['labels']['label_field'])
    if label_field not in holdout.columns:
        raise ValueError(f'holdout manifest must contain {label_field!r}')

    classes_mc = get_multiclass_class_names(cfg)
    name_to_idx = {c: i for i, c in enumerate(classes_mc)}
    binary_pain = cfg['labels']['binary_pain_class']

    holdout = holdout.drop_duplicates(subset=['snippet_id'])
    holdout['snippet_id'] = holdout['snippet_id'].astype(str)
    lab = holdout[label_field].astype(str).str.strip()
    holdout = holdout.loc[lab.isin(name_to_idx)].copy()
    holdout[label_field] = holdout[label_field].astype(str).str.strip()

    pose_index = load_pose_extraction_index(cfg)
    pose_v1_rel = Path(str(cfg['data']['pose_v1_dir']))
    if not pose_v1_rel.is_absolute():
        pose_v1_rel = REPO_ROOT / pose_v1_rel

    pose_paths: list[str | None] = []
    pose_versions: list[str] = []
    pose_masks: list[str | None] = []
    for _, row in holdout.iterrows():
        pth, ver, msk = _resolve_pose_row(row, pose_index, pose_v1_rel, cfg)
        pose_paths.append(pth)
        pose_versions.append(ver)
        pose_masks.append(msk)

    holdout = holdout.copy()
    holdout['pose_path'] = pose_paths
    holdout['pose_version'] = pose_versions
    holdout['pose_mask_path'] = pose_masks
    before_pose = len(holdout)
    holdout = holdout.loc[holdout['pose_path'].notna()].copy()
    logger.info('Holdout: %d rows with resolvable ViTPose files (%d / %d before drop)', len(holdout), len(holdout), before_pose)

    holdout = _apply_vitpose_qc(holdout, cfg, logger)

    holdout['label_int'] = holdout[label_field].map(name_to_idx)
    holdout['binary_label_int'] = (holdout[label_field] == binary_pain).astype(int)
    holdout['cat_id'] = holdout['video_id'].astype(str)

    if args.audio_confidence_filter is not None:
        conf_col = None
        if 'audio_mean_conf' in holdout.columns:
            conf_col = 'audio_mean_conf'
        elif 'audio_confidence' in holdout.columns:
            conf_col = 'audio_confidence'
        if conf_col is None:
            raise ValueError(
                'audio_confidence_filter requires audio_mean_conf or audio_confidence on holdout rows'
            )
        before = len(holdout)
        holdout = holdout[holdout[conf_col] >= args.audio_confidence_filter].copy()
        logger.info(
            'Applied audio confidence filter on %s >= %s: %d -> %d',
            conf_col, args.audio_confidence_filter, before, len(holdout),
        )

    holdout['pose_path'] = holdout['pose_path'].apply(lambda x: str(x).replace('\\', '/') if x is not None else None)
    if 'pose_mask_path' in holdout.columns:
        holdout['pose_mask_path'] = holdout['pose_mask_path'].apply(
            lambda x: str(x).replace('\\', '/') if x is not None and str(x).strip() else None
        )

    return holdout.reset_index(drop=True)


def distribution_counts(df: pd.DataFrame) -> dict[str, int]:
    return dict(Counter(df['audio_label_10'].astype(str).tolist()))


def split_holdout(df: pd.DataFrame, val_fraction: float, random_state: int, logger: logging.Logger) -> tuple[pd.DataFrame, pd.DataFrame]:
    if "audio_label_10" not in df.columns:
        raise ValueError("audio_label_10 missing for stratified split")
    if "cat_id" not in df.columns:
        raise ValueError("cat_id missing for group split")

    working = df.copy()
    working["audio_label_10"] = working["audio_label_10"].astype(str)
    split_classes = sorted(working["audio_label_10"].astype(str).unique())
    working["label_int"] = pd.Categorical(working["audio_label_10"], categories=split_classes, ordered=True).codes

    split_cfg = {
        'split': {
            'group_field': 'cat_id',
            'stratify_field': 'audio_label_10',
            'val_fraction': val_fraction,
            'random_state': random_state,
        }
    }
    meta_train, meta_val, split_msg = first_stratified_group_split(working, split_cfg)
    if split_msg is not None:
        logger.warning(f'first_stratified_group_split warning: {split_msg}')
    logger.info(f'Holdout split: train={len(meta_train)} val={len(meta_val)}')
    logger.info(f'Train class counts={distribution_counts(meta_train)}')
    logger.info(f'Val class counts={distribution_counts(meta_val)}')
    logger.info(f'Unique cats train/val={meta_train["cat_id"].nunique()}/{meta_val["cat_id"].nunique()}')
    return meta_train.reset_index(drop=True), meta_val.reset_index(drop=True)


def build_pair_specs(model_dirs: list[Path]) -> list[tuple[str, Path, dict[str, Any]]]:
    pairs: list[tuple[str, Path, dict[str, Any]]] = []
    for p in model_dirs:
        meta = load_pair_meta(p)
        neg = meta.get('class_neg_label_int_0')
        pos = meta.get('class_pos_label_int_1')
        if neg is None or pos is None:
            raise ValueError(f'pair_meta missing class fields in {p}')
        a = str(neg)
        b = str(pos)
        pair = f'{min(a, b)}|{max(a, b)}'
        pairs.append((str(pair), p, meta))
    pairs.sort(key=lambda x: x[0])
    return pairs


def build_model(model_dir: Path, cfg: dict[str, Any], device: torch.device, logger: logging.Logger) -> Any:
    ckpt = model_dir / 'training' / 'best_weights.pth'
    if not ckpt.exists():
        raise FileNotFoundError(f'missing checkpoint: {ckpt}')

    n_frames = int(cfg['data']['n_frames'])
    n_keypoints = int(cfg['data']['n_keypoints'])
    if n_keypoints != 17:
        raise ValueError(
            f'P4 pairwise checkpoints expect n_keypoints=17 (ViTPose); config has {n_keypoints}. '
            'Use model_training_v2/config_p4_pairwise.yaml.'
        )
    n_channels = int(cfg['data']['n_channels']) * 2

    model = P4PoseSTGCN(
        n_frames=n_frames,
        n_keypoints=n_keypoints,
        n_channels=n_channels,
        n_classes=2,
    ).to(device)

    blob = torch.load(ckpt, map_location=device)
    state = blob.get('model_state_dict', blob) if isinstance(blob, dict) else blob
    if not isinstance(state, dict):
        raise TypeError(f'Invalid checkpoint format: {ckpt}')
    model.load_state_dict(state, strict=True)
    model.eval()
    return model


def run_inference(model: Any, records: list[dict], cfg: dict[str, Any], batch_size: int, device: torch.device) -> tuple[list[str], np.ndarray]:
    infer_cfg = copy.deepcopy(cfg)
    infer_cfg.setdefault('training', {})['binary_only'] = True
    infer_cfg.setdefault('data', {})['pose_cache'] = {'backend': 'ram'}

    ds = PoseDataset(records, infer_cfg, is_train=False, use_kinematics=True)

    loader = DataLoader(ds, batch_size=batch_size, shuffle=False, drop_last=False, num_workers=0)
    snippet_ids: list[str] = []
    probs: list[float] = []

    with torch.no_grad():
        for batch in loader:
            pose = batch['pose'].to(device)
            mask = batch['mask'].to(device)
            logits = model(pose, mask)
            p1 = F.softmax(logits['logits_binary'], dim=1)[:, 1].detach().cpu().numpy()
            probs.extend([float(x) for x in p1])
            snippet_ids.extend([str(x) for x in batch['snippet_id']])

    return snippet_ids, np.array(probs, dtype=np.float32)


def compute_ece(y_true: np.ndarray, prob: np.ndarray, n_bins: int = 10) -> float:
    n_classes = prob.shape[1]
    n = len(y_true)
    y = y_true.astype(int)
    ece = 0.0
    for c in range(n_classes):
        ys = (y == c).astype(float)
        pc = prob[:, c]
        edges = np.linspace(0.0, 1.0, n_bins + 1)
        for b in range(n_bins):
            lo, hi = edges[b], edges[b + 1]
            if b < n_bins - 1:
                idx = (pc >= lo) & (pc < hi)
            else:
                idx = (pc >= lo) & (pc <= hi)
            if idx.sum() == 0:
                continue
            acc = ys[idx].mean()
            conf = pc[idx].mean()
            ece += (idx.sum() / n) * abs(acc - conf)
    return float(ece)


def calibration_table(prob: np.ndarray, y_true: np.ndarray, class_names: list[str], n_bins: int = 10) -> pd.DataFrame:
    rows: list[dict[str, Any]] = []
    y = y_true.astype(int)
    n_classes = prob.shape[1]
    edges = np.linspace(0.0, 1.0, n_bins + 1)
    for ci, cname in enumerate(class_names):
        ys = (y == ci).astype(float)
        pc = prob[:, ci]
        for bi in range(n_bins):
            lo, hi = edges[bi], edges[bi + 1]
            if bi < n_bins - 1:
                idx = (pc >= lo) & (pc < hi)
            else:
                idx = (pc >= lo) & (pc <= hi)
            cnt = int(idx.sum())
            rows.append(
                {
                    'class': cname,
                    'bin': bi,
                    'bin_start': float(lo),
                    'bin_end': float(hi),
                    'n_samples': cnt,
                    'avg_prob': float(pc[idx].mean()) if cnt else 0.0,
                    'positive_rate': float(ys[idx].mean()) if cnt else 0.0,
                }
            )
    return pd.DataFrame(rows)

