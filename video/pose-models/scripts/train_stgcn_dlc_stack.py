'''Stacking meta-learner over pairwise P4 (ViTPose / easy ViTPose) ST-GCN outputs.

Inference uses **ViTPose** ``.npy`` clips only (same pipeline as ``run_p4_pairwise.py``),
not DeepLabCut HDF5. Pass ``--config model_training_v2/config_p4_pairwise.yaml``.

This script trains a meta-classifier from OvO pairwise probabilities
P(class_pos|clip) generated by pre-trained binary ST-GCN models (typically
C(10,2)=45 directories; use ``--min-best-epoch`` to subset). By default the
target is **10-way** ``audio_label_10``. With ``--meta-binary-pain`` the target
is binary (pain vs non-pain) using ``labels.binary_pain_class``, with the same
pairwise probability features.

Optional: ``--min-best-epoch`` drops pairwise runs whose ``training/run_summary.json``
reports an early best checkpoint (0-based ``best_epoch``), which often correlates
with degenerate / collapsed training in hparam sweeps.

Optional: ``--pain-pair-models-only`` keeps only binary models whose ``pair_meta`` includes
``labels.binary_pain_class`` (typically 9 pairwise features from 45 for 10 classes). Unless
``--meta-binary-pain`` is set, the meta target remains **10-way** ``audio_label_10``.

Example (full grid, meta-train grouped CV, drop early-best base checkpoints, optional pain-only features):

  python -m model_training_v2.scripts.train_stgcn_dlc_stack \\
    --config model_training_v2/config_p4_pairwise.yaml \\
    --holdout-manifest path/to/holdout_manifest_audio10.jsonl \\
    --model-dirs-json path/to/stack_model_dirs_45.json \\
    --audio-confidence-filter 0.65 \\
    --cv-splits 3 \\
    --min-best-epoch 10 \\
    --pain-pair-models-only

Binary meta target (10-class labels collapsed to pain vs rest):

  ... same flags ... --meta-binary-pain

Why stacking on pairwise outputs
- The binary pairwise outputs preserve class boundaries from sub-problems.
- The meta stage learns cross-pair arbitration and calibration across all classes.

Why held-out data only
- Base binary models must not have seen these clips. Otherwise the meta-learner
  can overfit to correlated sub-model errors and produce overly optimistic
  estimates.

Why class_weight='balanced'
- Subclass frequencies are not uniform; weighting counters dominant class bias in
  the meta objective.

Why top-3 accuracy
- With 10 classes, top-1 can be too strict for operational triage. A
  top-3 metric captures useful rank-based performance.
'''

